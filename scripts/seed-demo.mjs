import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';
import { Client } from 'pg';
import mysql from 'mysql2/promise';

const root = fileURLToPath(new URL('../', import.meta.url));
const setting = (name, fallback) => process.env[`DB_TOOLKIT_DEMO_${name}`] || fallback;
const common = {
  user: setting('USER', 'toolkit_demo'),
  password: setting('PASSWORD', 'demo_password_local_only'),
  database: setting('DATABASE', 'toolkit_demo'),
};
const host = setting('HOST', '127.0.0.1');
assert(['127.0.0.1', 'localhost', '::1'].includes(host), 'Demo host must be loopback');
const sqlitePath = resolve(root, setting('SQLITE_FILE', 'data/demo/workspace-demo.sqlite'));

function fixtures() {
  const customers = Array.from({ length: 24 }, (_, i) => [i + 1, `Customer ${i + 1}`, i % 5 ? `customer${i + 1}@example.test` : null, i % 4 ? 'Cairo' : 'Alexandria', i === 0 ? "Notes with 'quotes', commas, and\na second line — مرحباً" : null]);
  const products = Array.from({ length: 12 }, (_, i) => [i + 1, `DEMO-${String(i + 1).padStart(3, '0')}`, ['Notebook', 'Desk lamp', 'Coffee mug', 'Keyboard'][i % 4] + ` ${i + 1}`, (12.5 + i * 7.25).toFixed(2), i % 3 ? 'Workspace' : null]);
  const orders = Array.from({ length: 150 }, (_, i) => [i + 1, i % 24 + 1, `2026-${String(i % 9 + 1).padStart(2, '0')}-${String(i % 27 + 1).padStart(2, '0')}`, ['pending', 'paid', 'shipped', 'cancelled'][i % 4], i % 7 ? null : 'Leave at reception']);
  const items = orders.flatMap(([id]) => [0, 1].map((offset) => {
    const product = products[(id + offset - 1) % products.length];
    return [(id - 1) * 2 + offset + 1, id, product[0], offset + 1, product[3]];
  }));
  return { customers, products, orders, order_items: items };
}

async function seed(kind, query) {
  const marker = `${kind}-demo`;
  const metadata = kind === 'sqlite'
    ? await query("SELECT name FROM sqlite_master WHERE type='table' AND name='demo_metadata'")
    : await query(`SELECT table_name FROM information_schema.tables WHERE table_schema = ${kind === 'mysql' ? 'DATABASE()' : "'public'"} AND table_name = 'demo_metadata'`);
  if (metadata.length) {
    const rows = await query('SELECT engine_marker FROM demo_metadata WHERE id = 1');
    assert.equal(rows[0]?.engine_marker, marker, 'Refusing database with a missing or different demo marker');
  } else {
    const existing = kind === 'sqlite'
      ? await query("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'")
      : await query(`SELECT table_name FROM information_schema.tables WHERE table_schema = ${kind === 'mysql' ? 'DATABASE()' : "'public'"} AND table_type = 'BASE TABLE'`);
    assert.equal(existing.length, 0, 'Refusing to seed an existing unmarked database');
  }
  const id = kind === 'mysql' ? 'INTEGER AUTO_INCREMENT PRIMARY KEY' : kind === 'postgres' ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const tables = [
    ['demo_metadata', 'id INTEGER PRIMARY KEY, engine_marker VARCHAR(32) NOT NULL'],
    ['customers', `id ${id}, name VARCHAR(120) NOT NULL, email VARCHAR(200) UNIQUE, city VARCHAR(100), notes TEXT`],
    ['products', `id ${id}, sku VARCHAR(32) NOT NULL UNIQUE, name VARCHAR(120) NOT NULL, price DECIMAL(12,2) NOT NULL, category VARCHAR(80)`],
    ['orders', `id ${id}, customer_id INTEGER NOT NULL REFERENCES customers(id), ordered_on DATE NOT NULL, status VARCHAR(20) NOT NULL, notes TEXT`],
    ['order_items', `id ${id}, order_id INTEGER NOT NULL REFERENCES orders(id), product_id INTEGER NOT NULL REFERENCES products(id), quantity INTEGER NOT NULL, unit_price DECIMAL(12,2) NOT NULL`],
  ];
  // MySQL requires table-level foreign key definitions to enforce these relationships.
  if (kind === 'mysql') {
    tables[3][1] = tables[3][1].replace(' REFERENCES customers(id)', '') + ', FOREIGN KEY (customer_id) REFERENCES customers(id)';
    tables[4][1] = tables[4][1].replace(' REFERENCES orders(id)', '').replace(' REFERENCES products(id)', '') + ', FOREIGN KEY (order_id) REFERENCES orders(id), FOREIGN KEY (product_id) REFERENCES products(id)';
  }
  for (const [name, definition] of tables) {
    await query(`CREATE TABLE IF NOT EXISTS ${name} (${definition})`);
    if (name === 'demo_metadata' && !metadata.length) await query(`INSERT INTO demo_metadata VALUES (1, '${marker}')`);
  }
  for (const [table, column] of [['orders', 'customer_id'], ['order_items', 'order_id'], ['order_items', 'product_id']]) {
    const name = `idx_${table}_${column}`;
    if (kind === 'mysql') {
      const found = await query('SELECT index_name FROM information_schema.statistics WHERE table_schema = DATABASE() AND table_name = ? AND index_name = ?', [table, name]);
      if (!found.length) await query(`CREATE INDEX ${name} ON ${table} (${column})`);
    } else await query(`CREATE INDEX IF NOT EXISTS ${name} ON ${table} (${column})`);
  }
  const data = { demo_metadata: [[1, marker]], ...fixtures() };
  const counts = {};
  for (let pass = 0; pass < 2; pass++) {
    await query(kind === 'mysql' ? 'START TRANSACTION' : 'BEGIN');
    try {
      for (const [table, rows] of Object.entries(data)) {
        for (const row of rows) {
          const placeholders = row.map((_, i) => kind === 'postgres' ? `$${i + 1}` : '?').join(', ');
          const conflict = kind === 'mysql' ? 'ON DUPLICATE KEY UPDATE id = id' : 'ON CONFLICT DO NOTHING';
          await query(`INSERT INTO ${table} VALUES (${placeholders}) ${conflict}`, row);
        }
      }
      await query('COMMIT');
    } catch (error) {
      await query('ROLLBACK');
      throw error;
    }
    for (const [table, rows] of Object.entries(data)) {
      const result = await query(`SELECT COUNT(*) AS total FROM ${table}`);
      const total = Number(result[0].total);
      assert(total >= rows.length, `${kind}.${table} has fewer than ${rows.length} rows`);
      if (pass) assert.equal(total, counts[table], `${kind}.${table} duplicated rows on rerun`);
      counts[table] = total;
    }
  }
  const views = kind === 'sqlite'
    ? await query("SELECT name FROM sqlite_master WHERE type='view' AND name='order_summary'")
    : await query(`SELECT table_name FROM information_schema.views WHERE table_schema = ${kind === 'mysql' ? 'DATABASE()' : "'public'"} AND table_name = 'order_summary'`);
  if (!views.length) await query(`CREATE VIEW order_summary AS SELECT o.id AS order_id, c.name AS customer_name, o.ordered_on, o.status, SUM(i.quantity * i.unit_price) AS total FROM orders o JOIN customers c ON c.id = o.customer_id JOIN order_items i ON i.order_id = o.id GROUP BY o.id, c.name, o.ordered_on, o.status`);
  assert.equal((await query('SELECT engine_marker FROM demo_metadata WHERE id = 1'))[0].engine_marker, marker);
  assert((await query('SELECT * FROM order_summary LIMIT 1')).length, 'Order summary must contain rows');
  // Explicit fixture IDs do not advance PostgreSQL identity sequences.
  if (kind === 'postgres') for (const table of Object.keys(fixtures())) await query(`SELECT setval(pg_get_serial_sequence('${table}', 'id'), GREATEST((SELECT MAX(id) FROM ${table}), (SELECT last_value FROM ${table}_id_seq)), true)`);
  console.log(JSON.stringify({ engine: kind, marker, counts, ...(kind === 'sqlite' ? { file: sqlitePath } : {}) }));
}

mkdirSync(dirname(sqlitePath), { recursive: true });
const sqlite = new DatabaseSync(sqlitePath);
try {
  sqlite.exec('PRAGMA foreign_keys = ON');
  await seed('sqlite', async (sql, params = []) => {
    const statement = sqlite.prepare(sql);
    return /^(SELECT|PRAGMA)\b/i.test(sql) ? statement.all(...params) : (statement.run(...params), []);
  });
} finally { sqlite.close(); }
const pg = new Client({ ...common, host, port: Number(setting('POSTGRES_PORT', '15432')) });
try {
  await pg.connect();
  await seed('postgres', async (sql, params = []) => (await pg.query(sql, params)).rows);
} finally { await pg.end(); }
const my = await mysql.createConnection({ ...common, host, port: Number(setting('MYSQL_PORT', '13306')) });
try {
  await seed('mysql', async (sql, params = []) => (await my.query(sql, params))[0]);
} finally { await my.end(); }
